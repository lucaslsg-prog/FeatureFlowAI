from __future__ import annotations

import json
import re
from pathlib import Path
from dataclasses import asdict

from domain.test_case import TestCase
from integrations.fit_insight_client import FitInsightClient
from services.file_service import FileService
from utils.prompts import load_test_case_prompt
from utils.sanitize import sanitize_llm_json


class TestCasePipeline:
    def __init__(self, file_service: FileService, fit_client: FitInsightClient):
        self.file_service = file_service
        self.fit_client = fit_client

    def process_file(self, file_path: str | Path, clean_name: str) -> list[dict]:
        if not Path(file_path).exists():
            raise FileNotFoundError(f"❌ File not found: {file_path}")

        if not self.fit_client.upload_file(file_path, clean_name):
            raise RuntimeError(f"❌ Upload Failed: {clean_name}")

        response = self.fit_client.send_chat_single_file(
            prompt=load_test_case_prompt(),
            filename=clean_name,
        )

        print("⚙️ LLM RESPONSE AS TEXT:", response.text)
        if response.status_code != 200:
            print(f"❌ Chat Failed: {clean_name}")
            return []

        if not response.text.strip():
            print("❌ Empty response from LLM")
            return []

        try:
            payload = response.json()
        except ValueError:
            return []

        if isinstance(payload, str):
            return self.parse_llm_testcases(payload)

        return []

    def parse_llm_testcases(self, llm_text: str) -> list[dict]:
        if llm_text is None:
            raise ValueError("LLM response is None (no content returned)")
        if isinstance(llm_text, dict):
            raise TypeError(f"LLM response is dict, expected string. Keys: {list(llm_text.keys())}")
        if not isinstance(llm_text, str):
            raise TypeError(f"Invalid LLM response type: {type(llm_text)}")

        match = re.search(r"\[\s*\{.*\}\s*\]", llm_text, re.S)
        if not match:
            raise ValueError("LLM response does not contain a valid JSON array of test cases.")

        json_str = sanitize_llm_json(match.group(0))
        if ".repeat(" in json_str:
            raise ValueError("LLM returned invalid JSON with JS expressions")

        try:
            data = json.loads(json_str)
        except json.JSONDecodeError as exc:
            raise ValueError(f"Invalid JSON generated by the LLM: {exc}\n\nSanitized JSON content:\n{json_str}") from exc

        if not isinstance(data, list):
            raise TypeError(f"Root JSON element must be a list, received: {type(data)}")

        normalized: list[dict] = []
        for index, tc in enumerate(data):
            if not isinstance(tc, dict):
                raise TypeError(f"Test case at index {index} is not a JSON object: {tc}")

            required_fields = ("descricao", "acoes", "dados", "resultadoEsperado")
            for field_name in required_fields:
                if field_name not in tc:
                    raise ValueError(f"Missing required field '{field_name}' in test case")

            if not isinstance(tc["acoes"], list):
                raise TypeError("'acoes' must be a list in test case")
            if not isinstance(tc["resultadoEsperado"], list):
                raise TypeError("'resultadoEsperado' must be a list in test case")
            if not isinstance(tc["dados"], dict):
                raise TypeError("'dados' must be a JSON object (dict) in test case")

            normalized.append(asdict(TestCase.from_dict(tc)))

        return normalized